# Neutral (league-average) defaults used when a park is unknown / too thin.
NEUTRAL_FACTOR = 1.0
NEUTRAL_ALTITUDE_FEET = 500


def load_computed_factors(conn, window_label: str = "rolling_2024_2026") -> int:
    """
    Refresh the in-process snapshot from the live ``mlb_teams.park_factors`` table.

    Lets long-running services load a freshly recomputed window without a code
    deploy. Mutates :data:`COMPUTED_PARK_FACTORS` in place and returns the number
    of parks loaded. Rows with a NULL factor are skipped (kept as unknown).

    Args:
        conn: psycopg2 connection (search_path including ``mlb_teams``).
        window_label: Which computed window to load.

    Returns:
        Count of parks loaded into the snapshot.
    """
    cur = conn.cursor()
    cur.execute(
        """
        SELECT home_team, runs_factor, hr_factor, hits_factor, n_games
          FROM mlb_teams.park_factors
         WHERE window_label = %s
        """,
        (window_label,),
    )
    loaded = 0
    fresh: Dict[str, Tuple[float, float, float, int]] = {}
    for team, runs, hr, hits, n_games in cur.fetchall():
        if runs is None or hr is None or hits is None:
            continue
        fresh[team] = (float(runs), float(hr), float(hits), int(n_games or 0))
        loaded += 1
    cur.close()
    if fresh:
        COMPUTED_PARK_FACTORS.clear()
        COMPUTED_PARK_FACTORS.update(fresh)
    return loaded


def _lookup(home_team: str, index: int) -> Optional[float]:
    """
    Return the ``index``-th factor (0=runs, 1=HR, 2=hits) for a team, or None.

    None is returned for unknown parks OR parks whose sample is below MIN_GAMES,
    so callers can distinguish "known factor" from "fall back to neutral".
    """
    canon = normalize_team_abbrev(home_team or "")
    entry = COMPUTED_PARK_FACTORS.get(canon)
    if entry is None:
        return None
    if entry[3] < MIN_GAMES:
        return None
    return entry[index]


def get_park_factor(home_team: str) -> Optional[float]:
    """
    Computed overall RUNS park factor as a multiplier (1.00 = neutral).

    Args:
        home_team: Team abbreviation in any common form (normalized to canonical).

    Returns:
        Runs park factor (e.g. 1.24 = +24% run environment), or ``None`` if the
        park is unknown or its sample is below ``MIN_GAMES``.
    """
    val = _lookup(home_team, 0)
    return round(val, 3) if val is not None else None


def get_park_factor_100(home_team: str) -> Optional[int]:
    """Return the runs park factor on the 100=neutral scale, or None."""
    val = _lookup(home_team, 0)
    return int(round(val * 100)) if val is not None else None


def get_park_hr_factor(home_team: str) -> float:
    """
    Computed per-park HOME-RUN factor as a multiplier (1.00 = neutral).

    Falls back to ``NEUTRAL_FACTOR`` when the park is unknown or too thin.

    Args:
        home_team: Team abbreviation in any common form (normalized to canonical).

    Returns:
        HR park-factor multiplier (e.g. 1.18 = +18% HR environment).
    """
    val = _lookup(home_team, 1)
    return round(val, 3) if val is not None else NEUTRAL_FACTOR


def get_park_hits_factor(home_team: str) -> float:
    """
    Computed per-park HITS factor as a multiplier (1.00 = neutral).

    Falls back to ``NEUTRAL_FACTOR`` when the park is unknown or too thin.

    Args:
        home_team: Team abbreviation in any common form (normalized to canonical).

    Returns:
        Hits park-factor multiplier (e.g. 1.23 = +23% hits environment).
    """
    val = _lookup(home_team, 2)
    return round(val, 3) if val is not None else NEUTRAL_FACTOR


def get_park_altitude(home_team: str) -> int:
    """
    Venue altitude in feet above sea level (physical constant).

    Args:
        home_team: Team abbreviation in any common form (normalized to canonical).

    Returns:
        Altitude in feet, or ``NEUTRAL_ALTITUDE_FEET`` if the park is unknown.
    """
    return PARK_ALTITUDE_FEET.get(normalize_team_abbrev(home_team or ""), NEUTRAL_ALTITUDE_FEET)


def get_park_sub_factors(home_team: str, batter_hand: Optional[str] = None) -> Dict[str, float]:
    """
    Bundle all computed park sub-factors for a home team in one lookup.

    ``batter_hand`` is accepted for interface compatibility with hand-split park
    factors. We do NOT compute hand splits (our game logs do not carry the
    batted-ball hand context needed), so the same (real, hand-agnostic) factor is
    returned regardless of hand; ``park_batter_hand_known`` records whether a
    valid hand ('L'/'R'/'S') was supplied so downstream code can tell the factor
    is hand-agnostic by design (not by missing data).

    ``park_factors_known`` is 1.0 when the park has a trusted computed factor
    (sample >= ``MIN_GAMES``), else 0.0 (and the HR/hits factors fall back to
    neutral) - never a guessed proxy.

    Args:
        home_team: Home team abbreviation (any common form).
        batter_hand: Optional batter handedness ('L', 'R', 'S'). Reserved.

    Returns:
        Dict with ``park_hr_factor``, ``park_hits_factor``, ``park_runs_factor``,
        ``park_altitude_feet``, ``park_is_coors``, ``park_factors_known``, and
        ``park_batter_hand_known``.
    """
    hand = (batter_hand or "").strip().upper()
    runs = _lookup(home_team, 0)
    return {
        "park_runs_factor": round(runs, 3) if runs is not None else NEUTRAL_FACTOR,
        "park_hr_factor": get_park_hr_factor(home_team),
        "park_hits_factor": get_park_hits_factor(home_team),
        "park_altitude_feet": float(get_park_altitude(home_team)),
        "park_is_coors": 1.0 if normalize_team_abbrev(home_team or "") == "COL" else 0.0,
        "park_factors_known": 1.0 if runs is not None else 0.0,
        "park_batter_hand_known": 1.0 if hand in ("L", "R", "S") else 0.0,
    }
