"""
MLB Park Factors (computed from the stored games)
=================================================
Park factors used to enrich the sabermetric and volume features. Every factor here
is computed from the stored games by
``mlb/scripts/loaders/compute_park_factors.py`` and persisted to
``mlb_teams.park_factors``. This module embeds that computed snapshot as the
in-process lookup (so feature extractors need no DB round-trip) and can also
refresh the snapshot live from the table via :func:`load_computed_factors`.

How the factors were computed (see the loader docstring for the full method):
  - ``runs_factor``  = (runs/game at the venue, home+away combined)
                       / (league runs/game), from ``mlb_games.games`` scores.
  - ``hr_factor``    = (HR/game at the venue)   / (league HR/game)
  - ``hits_factor``  = (hits/game at the venue) / (league hits/game)
    HR and hits per game are aggregated from ``mlb_players.batter_game_logs``
    (both teams' batting lines) joined to games by ``game_id`` -> home_team.
  Window: rolling multi-season (2024-2026). 1.0 = league-neutral.

Each factor carries ``n_games``; when a park's sample is below ``MIN_GAMES`` the
lookups fall back to neutral and expose ``*_known = 0`` rather than ship a thin
estimate. Unknown parks also return neutral with ``*_known = 0``.

ALTITUDE is a PHYSICAL CONSTANT (official venue elevation, feet above sea level),
not a statistic, so it remains a documented lookup. Verified sane (Coors ~5,200
ft is the extreme; everything else near sea level).

------------------------------------------------------------------------------
GENERATED SNAPSHOT
------------------------------------------------------------------------------
The ``COMPUTED_PARK_FACTORS`` dict below was generated by
``python -m mlb.scripts.loaders.compute_park_factors --start 2024 --end 2026``
on 2026-06-19 (window ``rolling_2024_2026``, 7,365 qualifying games). Re-run that
loader and re-export to refresh; or call :func:`load_computed_factors` at runtime
to read the live ``mlb_teams.park_factors`` table.
"""

