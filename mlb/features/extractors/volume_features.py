"""
Volume / Opportunity Feature Extractor (MLB)
============================================
Opportunity features - how many chances a player is likely to get - which the
sabermetric rate stats then scale into expected production.

Where the constants come from:
  - The lineup-slot -> expected-PA curve is computed from the data (mean PA/game per
    starting slot from our own ``batter_lineup_slots`` JOIN ``batter_game_logs``),
    computed and persisted by ``mlb/scripts/loaders/compute_expected_pa.py`` and
    embedded below as a generated snapshot (refreshable live via
    :func:`load_computed_expected_pa`).
  - The opposing-bullpen FIP uses the target season's league-computed FIP constant
    (``season_fip_constant``), not a fixed 3.10.

BATTER stats (HITS / TOTAL_BASES)
---------------------------------
  - ``volume_lineup_slot``  The batter's lineup slot for THIS game. The current
        game's announced batting order is known pre-game (NOT leakage), so if the
        caller passes ``lineup_slot`` it is used directly. Otherwise we fall back
        to the batter's RECENT TYPICAL slot (mode of slots in
        ``batter_lineup_slots`` STRICTLY before the target date).
  - ``volume_recent_typical_slot``  Pre-date modal lineup slot (always pre-date).
  - ``volume_slot_known``   1.0 if a current or recent slot was resolved, else 0.
  - ``volume_expected_pa``  Expected plate appearances, from the computed
        slot -> mean-PA/game curve (see ``SLOT_EXPECTED_PA`` below).
  - ``volume_slot_games_sample``  Number of pre-date lineup rows seen.

PITCHER stat (STRIKEOUTS) / opponent context
----------------------------------------------
  - ``volume_opp_bullpen_fip``  The OPPOSING team's bullpen (non-starter pitchers)
        rolling FIP over a trailing window, STRICTLY before the target date, using
        the target season's league-computed FIP constant. The starter in each
        opposing game is the pitcher with the most batters faced for that
        ``game_id``; everyone else is bullpen.
  - ``volume_opp_bullpen_k_per_9``  Same bullpen population, rolling K/9.
  - ``volume_opp_bullpen_games_sample``

Leakage: ``volume_recent_typical_slot``, ``volume_opp_bullpen_*`` use ONLY rows
with ``game_date`` strictly before the target date. The CURRENT game's announced
slot (passed in by the caller) is pre-game public information.

``days_rest`` lives in ``temporal_features`` and is NOT duplicated here.
"""

import logging
from collections import Counter
from typing import Any, Dict, Optional, Tuple

from .base import BaseFeatureExtractor
from .sabermetric_features import FALLBACK_FIP_CONSTANT, season_fip_constant

logger = logging.getLogger(__name__)

BATTER_STATS = ("HITS", "TOTAL_BASES")

# Computed lineup-slot -> expected PA/game curve. slot -> (mean_pa, n_games).
# GENERATED by mlb.scripts.loaders.compute_expected_pa (window rolling_2024_2026)
# from mlb_players.batter_lineup_slots JOIN batter_game_logs. DO NOT hand-edit -
# regenerate from the loader. n_games is the sample behind each mean.
SLOT_EXPECTED_PA_SNAPSHOT: Dict[int, Tuple[float, int]] = {
    1: (4.1497, 10768),
    2: (4.0363, 10790),
    3: (3.9273, 10867),
    4: (3.8317, 10872),
    5: (3.6763, 11024),
    6: (3.5371, 11173),
    7: (3.3503, 11448),
    8: (3.1735, 11714),
    9: (2.9118, 12377),
}

# Flat slot -> mean-PA map used by the extractor (derived from the snapshot).
SLOT_EXPECTED_PA: Dict[int, float] = {
    slot: mean_pa for slot, (mean_pa, _n) in SLOT_EXPECTED_PA_SNAPSHOT.items()
}

# Neutral fallback expected-PA when the slot is unknown: the overall mean of the
# per-slot means. Recomputed at import from the snapshot so it tracks the curve.
DEFAULT_EXPECTED_PA = round(sum(v for v in SLOT_EXPECTED_PA.values()) / len(SLOT_EXPECTED_PA), 4)

# Rolling window (days) for the opposing-bullpen FIP aggregation.
BULLPEN_WINDOW_DAYS = 30


def load_computed_expected_pa(conn, window_label: str = "rolling_2024_2026") -> int:
    """
    Refresh the in-process slot -> expected-PA curve from the live
    ``mlb_teams.expected_pa_by_slot`` table.

    Lets long-running services load a freshly recomputed curve without a code
    deploy. Mutates :data:`SLOT_EXPECTED_PA` / :data:`SLOT_EXPECTED_PA_SNAPSHOT`
    in place and returns the number of slots loaded. Rows with a NULL mean_pa are
    skipped.

    Args:
        conn: psycopg2 connection (search_path including ``mlb_teams``).
        window_label: Which computed window to load.

    Returns:
        Count of slots loaded.
    """
    cur = conn.cursor()
    cur.execute(
        """
        SELECT lineup_slot, mean_pa, n_games
          FROM mlb_teams.expected_pa_by_slot
         WHERE window_label = %s
        """,
        (window_label,),
    )
    fresh: Dict[int, Tuple[float, int]] = {}
    for slot, mean_pa, n_games in cur.fetchall():
        if mean_pa is None:
            continue
        fresh[int(slot)] = (round(float(mean_pa), 4), int(n_games or 0))
    cur.close()
    if fresh:
        SLOT_EXPECTED_PA_SNAPSHOT.clear()
        SLOT_EXPECTED_PA_SNAPSHOT.update(fresh)
        SLOT_EXPECTED_PA.clear()
        SLOT_EXPECTED_PA.update({s: mp for s, (mp, _n) in fresh.items()})
    return len(fresh)


class VolumeFeatureExtractor(BaseFeatureExtractor):
    """Lineup-slot / expected-PA (batters) and opposing-bullpen FIP (pitchers)."""

    FEATURE_NAMES = (
        # Batter opportunity
        "volume_lineup_slot",
        "volume_recent_typical_slot",
        "volume_slot_known",
        "volume_expected_pa",
        "volume_slot_games_sample",
        # Opposing bullpen (pitcher stat / opponent context)
        "volume_opp_bullpen_fip",
        "volume_opp_bullpen_k_per_9",
        "volume_opp_bullpen_games_sample",
    )

    def __init__(self, conn: Any):
        """
        Args:
            conn: Connection to the ``mlb_players`` schema (lineup slots + pitcher
                  game logs).
        """
        super().__init__(conn, name="VolumeFeatures")
        self._fip_const_cache: Dict[int, float] = {}

    @classmethod
    def get_defaults(cls) -> Dict[str, float]:
        return {
            "volume_lineup_slot": 0.0,
            "volume_recent_typical_slot": 0.0,
            "volume_slot_known": 0.0,
            "volume_expected_pa": DEFAULT_EXPECTED_PA,
            "volume_slot_games_sample": 0.0,
            "volume_opp_bullpen_fip": 4.20,
            "volume_opp_bullpen_k_per_9": 8.5,
            "volume_opp_bullpen_games_sample": 0.0,
        }

    def _season_fip_constant(self, season: int) -> float:
        """Cached per-season league FIP constant (shared implementation)."""
        if season in self._fip_const_cache:
            return self._fip_const_cache[season]
        const = season_fip_constant(self, season)
        self._fip_const_cache[season] = const
        return const

    def extract(
        self,
        player_name: str,
        game_date: Any,
        stat_type: str = "HITS",
        opponent: Optional[str] = None,
        lineup_slot: Optional[int] = None,
        **kwargs,
    ) -> Dict[str, float]:
        """
        Extract volume / opportunity features.

        Args:
            player_name: Batter (batter stats) full name; ignored for the
                opposing-bullpen lookup which keys on ``opponent``.
            game_date: Target game date (pre-date cutoff for typical slot / bullpen).
            stat_type: Selects which feature group(s) to populate.
            opponent: Opposing team abbreviation (drives ``opp_bullpen_*``).
            lineup_slot: Announced current-game batting slot (pre-game, NOT
                leakage). Used directly when supplied.

        Returns:
            Dict of volume features (defaults for the inapplicable role).
        """
        game_date_str = self._normalize_date(game_date)
        features = self.get_defaults()

        if stat_type.upper() in BATTER_STATS:
            self._batter_opportunity(player_name, game_date_str, lineup_slot, features)

        if opponent:
            self._opp_bullpen(opponent, game_date_str, features)

        return features

    # ------------------------------------------------------------------ #
    # Batter opportunity
    # ------------------------------------------------------------------ #
    def _batter_opportunity(
        self,
        player_name: str,
        game_date_str: str,
        lineup_slot: Optional[int],
        features: Dict[str, float],
    ) -> None:
        """Resolve typical slot (pre-date) and expected PA into ``features``."""
        query = """
            SELECT bls.batting_order
            FROM batter_lineup_slots bls
            JOIN batter_profile bp ON bls.player_id = bp.player_id
            WHERE unaccent(bp.full_name) = unaccent(%s)
              AND bls.game_date < %s
              AND bls.batting_order BETWEEN 1 AND 9
            ORDER BY bls.game_date DESC
            LIMIT 20
        """
        df = self._safe_query(query, (player_name, game_date_str))

        typical_slot = 0
        if df is not None and len(df) > 0:
            slots = [int(v) for v in df["batting_order"].tolist() if v is not None]
            if slots:
                typical_slot = Counter(slots).most_common(1)[0][0]
                features["volume_recent_typical_slot"] = float(typical_slot)
                features["volume_slot_games_sample"] = float(len(slots))

        # Current announced slot wins; else fall back to recent typical.
        current_slot = self._coerce_slot(lineup_slot)
        resolved = current_slot if current_slot else typical_slot

        if resolved:
            features["volume_lineup_slot"] = float(resolved)
            features["volume_slot_known"] = 1.0
            features["volume_expected_pa"] = SLOT_EXPECTED_PA.get(resolved, DEFAULT_EXPECTED_PA)

    @staticmethod
    def _coerce_slot(value: Any) -> int:
        """Coerce an announced slot to an int in 1..9, or 0 if invalid."""
        if value is None:
            return 0
        try:
            slot = int(value)
        except (ValueError, TypeError):
            return 0
        return slot if 1 <= slot <= 9 else 0

    # ------------------------------------------------------------------ #
    # Opposing bullpen FIP
    # ------------------------------------------------------------------ #
    def _opp_bullpen(self, opponent: str, game_date_str: str, features: Dict[str, float]) -> None:
        """Compute opposing-bullpen rolling FIP / K9 into ``features``."""
        # Bullpen = opponent-team pitcher-games that were NOT the game's starter.
        # The starter is the opponent pitcher with the most batters_faced for that
        # game_id. We exclude those rows and aggregate the rest over the window.
        query = """
            SELECT
                COUNT(*)::float                          AS games,
                COALESCE(SUM(pgl.innings_pitched), 0)    AS ip,
                COALESCE(SUM(pgl.strikeouts), 0)         AS k,
                COALESCE(SUM(pgl.walks), 0)              AS bb,
                COALESCE(SUM(pgl.home_runs_allowed), 0)  AS hr
            FROM pitcher_game_logs pgl
            WHERE pgl.team = %s
              AND pgl.game_date < %s
              AND pgl.game_date >= (%s::date - make_interval(days => %s))
              AND pgl.id <> (
                  SELECT sp.id
                  FROM pitcher_game_logs sp
                  WHERE sp.game_id = pgl.game_id AND sp.team = pgl.team
                  ORDER BY sp.batters_faced DESC NULLS LAST
                  LIMIT 1
              )
        """
        df = self._safe_query(
            query,
            (opponent, game_date_str, game_date_str, BULLPEN_WINDOW_DAYS),
        )
        if df is None or len(df) == 0:
            return

        row = df.iloc[0]
        games = self._safe_float(row["games"], 0.0)
        if games <= 0:
            return

        ip = self._safe_float(row["ip"], 0.0)
        k = self._safe_float(row["k"], 0.0)
        bb = self._safe_float(row["bb"], 0.0)
        hr = self._safe_float(row["hr"], 0.0)

        features["volume_opp_bullpen_games_sample"] = games
        if ip > 0:
            fip_const = self._season_fip_constant(int(game_date_str[:4]))
            features["volume_opp_bullpen_fip"] = (13.0 * hr + 3.0 * bb - 2.0 * k) / ip + fip_const
            features["volume_opp_bullpen_k_per_9"] = k / ip * 9.0


# Re-exported for callers/tests that referenced the old name. The FIP constant is
# now season-computed; this is only the documented FALLBACK used when the league
# pass is unavailable.
FIP_CONSTANT = FALLBACK_FIP_CONSTANT
